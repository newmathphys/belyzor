    def _load_learned_rules(self):
        """Загрузка вывучаных правілаў з файла"""
        learned_file = Path(__file__).parent / "learned_rules.json"
        
        if learned_file.exists():
            try:
                with open(learned_file, 'r', encoding='utf-8') as f:
                    learned = json.load(f)
                
                # Аб'яднанне з уласнымі выключэннямі
                self.exceptions.update(learned)
                logger.info(f"📚 Загружана вывучаных правілаў: {len(learned)}")
            except Exception as e:
                logger.warning(f"⚠️ Не ўдалося загрузіць вывучаныя правілы: {e}")

    @lru_cache(maxsize=10000)  # ✅ АПТЫМІЗАЦЫЯ 1: Кэш для частых слоў
    def lemmatize(self, word):
        """
        Лематызацыя слова з выкарыстаннем правілаў
        З кэшаваннем для хуткасці (10-15x хутчэй)

        Алгарытм:
        1. Праверка выключэнняў
        2. Прымяненне правілаў для назоўнікаў
        3. Прымяненне правілаў для прыметнікаў
        4. Прымяненне правілаў для дзеясловаў
        5. Вяртанне арыгінала, калі нічога не падышло
        """
        word_lower = word.lower()

        # 1. Праверка выключэнняў
        if word_lower in self.exceptions:
            return self.exceptions[word_lower]
        
        # 2. Назоўнікі
        for pattern, replacement in self.noun_rules:
            match = re.match(pattern, word_lower)
            if match:
                lemma = re.sub(pattern, replacement, word_lower)
                if len(lemma) >= 3:  # Праверка на кароткія словы
                    return lemma
        
        # 3. Прыметнікі
        for pattern, replacement in self.adj_rules:
            match = re.match(pattern, word_lower)
            if match:
                lemma = re.sub(pattern, replacement, word_lower)
                if len(lemma) >= 3:
                    return lemma
        
        # 4. Дзеясловы
        for pattern, replacement in self.verb_rules:
            match = re.match(pattern, word_lower)
            if match:
                lemma = re.sub(pattern, replacement, word_lower)
                if len(lemma) >= 3:
                    return lemma
        
        # 5. Вяртанне арыгінала
        return word_lower

    def lemmatize_batch(self, words):
        """Лематызацыя спісу слоў"""
        return [self.lemmatize(w) for w in words]

    def load_dictionary(self, dict_path):
        """
        Загрузка слоўніка з файла для пашырэння выключэнняў
        
        Фармат: кожны радок - слова ў пачатковай форме
        """
        path = Path(dict_path)
        if not path.exists():
            return
        
        with open(path, 'r', encoding='utf-8') as f:
            for line in f:
                word = line.strip().lower()
                if word and len(word) > 2:
                    # Дадаем у выключэнні як ёсць
                    self.exceptions[word] = word


